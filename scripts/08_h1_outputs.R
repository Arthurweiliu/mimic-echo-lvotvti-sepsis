# 08_h1_outputs.R — Table1(完整) + 森林图 (per +5 cm)
# --- portable working directory: 1st CLI argument, else this script's own directory ---
{ .a <- grep('^--file=', commandArgs(FALSE), value=TRUE)
  setwd(if (length(.a)) dirname(normalizePath(sub('^--file=', '', .a[1]))) else getwd()) }
num<-function(x) suppressWarnings(as.numeric(x))
d<-read.csv('h1_data.csv',stringsAsFactors=FALSE)
for(v in c('age','sofa','sapsii','charlson','lactate','creat','mbp_min','hr_mean','temp_mean','spo2_min',
           'lvef','norepi','bun','hgb','plt','wbc','bili','inr','troponin','vti','fu_days','event90')) d[[v]]<-num(d[[v]])
d$vent<-d$vent=='t'; d$rrt<-d$rrt=='t'; d$vaso<-as.numeric(!is.na(d$norepi)&d$norepi>0)
d<-d[!is.na(d$vti)&d$vti>0,]
lev<-c('<17','17-20','>20')
d$vcat<-factor(ifelse(d$vti<17,'<17', ifelse(d$vti<=20,'17-20','>20')), levels=lev)
med<-function(x) sprintf('%.1f (%.1f-%.1f)', median(x,na.rm=TRUE), quantile(x,.25,na.rm=TRUE), quantile(x,.75,na.rm=TRUE))
ppct<-function(x) sprintf('%d (%.0f%%)', sum(x,na.rm=TRUE), mean(x,na.rm=TRUE)*100)
pv_k<-function(x) tryCatch(format(kruskal.test(x~d$vcat)$p.value, digits=2, scientific=TRUE), error=function(e)'NA')
pv_c<-function(x) tryCatch(format(suppressWarnings(chisq.test(table(d$vcat, x)))$p.value, digits=2, scientific=TRUE), error=function(e)'NA')
rows<-list(); addC<-function(lbl,fn,pf) rows[[length(rows)+1]]<<-c(lbl, sapply(lev,function(g) fn(d[d$vcat==g,])), pf)
addC('N', function(x) as.character(nrow(x)), '')
addC('Age, median (IQR), years', function(x) med(x$age), pv_k(d$age))
addC('Female, n (%)', function(x) sprintf('%d (%.0f%%)', sum(x$sex=='F',na.rm=TRUE), mean(x$sex=='F',na.rm=TRUE)*100), pv_c(d$sex=='F'))
addC('SOFA (first day)', function(x) med(x$sofa), pv_k(d$sofa))
addC('SAPS-II', function(x) med(x$sapsii), pv_k(d$sapsii))
addC('Charlson index', function(x) med(x$charlson), pv_k(d$charlson))
addC('Lactate, mmol/L', function(x) med(x$lactate), pv_k(d$lactate))
addC('Creatinine, mg/dL', function(x) med(x$creat), pv_k(d$creat))
addC('BUN, mg/dL', function(x) med(x$bun), pv_k(d$bun))
addC('Hemoglobin, g/dL', function(x) med(x$hgb), pv_k(d$hgb))
addC('Platelets, K/uL', function(x) med(x$plt), pv_k(d$plt))
addC('WBC, K/uL', function(x) med(x$wbc), pv_k(d$wbc))
addC('Bilirubin total, mg/dL', function(x) med(x$bili), pv_k(d$bili))
addC('INR', function(x) med(x$inr), pv_k(d$inr))
addC('Troponin T (24 h), ng/mL', function(x) med(x$troponin), pv_k(d$troponin))
addC('MAP minimum, mm Hg', function(x) med(x$mbp_min), pv_k(d$mbp_min))
addC('Heart rate, mean, bpm', function(x) med(x$hr_mean), pv_k(d$hr_mean))
addC('LVEF, %', function(x) med(x$lvef), pv_k(d$lvef))
addC('Vasopressor (24 h), n (%)', function(x) sprintf('%d (%.0f%%)', sum(x$vaso), mean(x$vaso)*100), pv_c(d$vaso))
addC('Invasive MV (24 h), n (%)', function(x) ppct(x$vent), pv_c(d$vent))
addC('RRT (7 d), n (%)', function(x) ppct(x$rrt), pv_c(d$rrt))
addC('90-day mortality, n (%)', function(x) ppct(x$event90), pv_c(d$event90))
tab<-do.call(rbind,rows); colnames(tab)<-c('Variable', lev, 'p')
write.csv(tab,'H1_Table1.csv',row.names=FALSE)
cat('Table1 rows:',nrow(tab),'cols:',paste(colnames(tab),collapse=' | '),'\n')
print(tab)
