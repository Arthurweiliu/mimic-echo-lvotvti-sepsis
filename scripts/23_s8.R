# 23_s8.R — Table S8: 有/无 LVOT-VTI 基线比较
# --- portable working directory: 1st CLI argument, else this script's own directory ---
{ .a <- grep('^--file=', commandArgs(FALSE), value=TRUE)
  setwd(if (length(.a)) dirname(normalizePath(sub('^--file=', '', .a[1]))) else getwd()) }
num<-function(x) suppressWarnings(as.numeric(x))
d<-read.csv('h1_data.csv',stringsAsFactors=FALSE)  # first-ICU 12,120
for(v in c('age','sofa','sapsii','charlson','lactate','creat','norepi','fu_days','event90','vti')) d[[v]]<-num(d[[v]])
d$vent<-d$vent=='t'; d$vaso<-as.numeric(!is.na(d$norepi)&d$norepi>0)
d$avail<-as.numeric(!is.na(d$vti)&d$vti>0)
med<-function(x) sprintf('%.1f (%.1f-%.1f)', median(x,na.rm=TRUE), quantile(x,.25,na.rm=TRUE), quantile(x,.75,na.rm=TRUE))
pct<-function(x) sprintf('%d (%.0f%%)', sum(x,na.rm=TRUE), mean(x,na.rm=TRUE)*100)
pk<-function(v) tryCatch(format(kruskal.test(v~d$avail)$p.value,digits=2,scientific=TRUE),error=function(e)'NA')
pc<-function(v) tryCatch(format(suppressWarnings(chisq.test(table(d$avail,v)))$p.value,digits=2,scientific=TRUE),error=function(e)'NA')
rows<-list(); add<-function(lbl,f,pf) rows[[length(rows)+1]]<<-c(lbl, f(d[d$avail==1,]), f(d[d$avail==0,]), pf)
add('N', function(x) as.character(nrow(x)),'')
add('Age, years', function(x) med(x$age), pk(d$age))
add('Female, n (%)', function(x) sprintf('%d (%.0f%%)', sum(x$sex=='F'), mean(x$sex=='F')*100), pc(d$sex=='F'))
add('SOFA (first day)', function(x) med(x$sofa), pk(d$sofa))
add('SAPS-II', function(x) med(x$sapsii), pk(d$sapsii))
add('Charlson index', function(x) med(x$charlson), pk(d$charlson))
add('Lactate, mmol/L', function(x) med(x$lactate), pk(d$lactate))
add('Creatinine, mg/dL', function(x) med(x$creat), pk(d$creat))
add('Invasive MV (24 h), n (%)', function(x) pct(x$vent), pc(d$vent))
add('Vasopressor (24 h), n (%)', function(x) pct(x$vaso), pc(d$vaso))
add('90-day mortality, n (%)', function(x) pct(x$event90), pc(d$event90))
tab<-do.call(rbind,rows); colnames(tab)<-c('Variable','LVOT-VTI available (n=7,253)','LVOT-VTI missing (n=4,867)','p')
write.csv(tab,'H1_TableS8.csv',row.names=FALSE); print(tab)
